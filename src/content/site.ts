/** Все ли обязательные реквизиты заполнены. От этого зависит предупреждение
 *  в подвале: пока данные выдуманы, сайт обязан сам об этом говорить. */
/**
 * Проверка ИНН по контрольной сумме.
 *
 * Последние цифры ИНН вычисляются из предыдущих по формуле налоговой,
 * поэтому опечатку видно, не спрашивая никого. Без этой проверки неверный
 * номер молча встанет на страницу реквизитов и в оферту — а его сверяют
 * и банк, и платёжный сервис, и покупатель через сайт ФНС.
 */
export function validInn(inn: string): boolean {
  const d = inn.replace(/\D/g, '');
  if (d.length !== 12) return false;
  const n = [...d].map(Number);
  const check = (coef: number[]) =>
    (coef.reduce((s, c, i) => s + c * n[i], 0) % 11) % 10;
  return check([7, 2, 4, 10, 3, 5, 9, 4, 6, 8]) === n[10]
      && check([3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]) === n[11];
}

