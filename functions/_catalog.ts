/**
 * КАТАЛОГ ДЛЯ СБОРКИ — снимок того, что лежит в базе.
 *
 * Источник правды — таблицы `products` и `product_sizes` в D1: оттуда берут
 * данные и оформление заказа, и живая витрина. Но страницы собираются
 * статикой, и в момент сборки базы под рукой нет — поэтому перед каждой
 * сборкой `scripts/sync-catalog.mjs` выгружает каталог в `_catalog.json`,
 * а этот файл его читает.
 *
 * Отсюда два правила:
 *   — руками `_catalog.json` не правят, его перезапишет следующая сборка;
 *   — цены на витрине могут отстать от базы ровно до следующей публикации,
 *     поэтому `src/scripts/live.ts` подтягивает свежие при открытии страницы.
 *
 * Цену, пришедшую из браузера, сервер не использует НИКОГДА — только id,
 * размер и количество. Иначе сумму заказа меняют в инструментах разработчика.
 */
import snapshot from './_catalog.json';

export type Product = {
  id: string;
  name: string;
  category: 'Верх' | 'Низ' | 'Верхняя одежда' | 'Аксессуары';
  price: number;
  oldPrice?: number;
  colour: string;
  composition: string;
  sizes: string[];
  /** Сколько осталось по каждому размеру. */
  stock: Record<string, number>;
  text: string;
  photo: string;
  /** Метка «часто берут». Ставить ОДНОМУ товару: метка на трети
   *  ассортимента не выделяет ничего и перестаёт работать. */
  hit?: boolean;
};

// Через unknown: из JSON TypeScript выводит тип с точным перечнем ключей
// каждого размера, и он не сходится с Record<string, number> буквально.
// Форму снимка гарантирует скрипт выгрузки, а не система типов.
export const products = snapshot as unknown as Product[];
